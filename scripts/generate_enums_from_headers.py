"""Regenerate Expedition/enums.py from reference/expedition/*.h.

Usage:
    uv run python scripts/generate_enums_from_headers.py          # print to stdout
    uv run python scripts/generate_enums_from_headers.py --write  # rewrite enums.py
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Dict, List, Optional

sys.path.insert(0, str(Path(__file__).resolve().parent))

from _header_enums import (  # noqa: E402
    ENUM_SPECS,
    REFERENCE_DIR,
    REPO_ROOT,
    find_missing_headers,
    load_enums,
)

OUTPUT_PATH = REPO_ROOT / "Expedition" / "enums.py"

DOCSTRINGS = {
    "Var": "Enumeration of Expedition variables (per-boat channels, ExChannels).",
    "SysVar": "Enumeration of system variables (ExSysChannels).",
    "SysBooleanVar": "Enumeration of system boolean variables (ExSysBooleanChannels).",
    "SysIntVar": "Enumeration of system integer variables (ExSysIntChannels).",
}


def render(enums: Dict[str, Dict[str, int]], header_source: str) -> str:
    lines: List[str] = [
        '"""Expedition channel enumerations.',
        "",
        "Generated by scripts/generate_enums_from_headers.py from the Expedition headers.",
        "Do not edit by hand. Re-run the generator after syncing headers.",
        f"Header source: {header_source}",
        '"""',
        "",
        "from enum import IntEnum",
    ]
    for spec in ENUM_SPECS:
        members = enums[spec.py_name]
        # Two blank lines before each top-level class, as black would format it.
        lines.append("")
        lines.append("")
        lines.append(f"class {spec.py_name}(IntEnum):")
        lines.append(f'    """{DOCSTRINGS[spec.py_name]}"""')
        lines.append("")
        canonical_values = {}
        for name, value in members.items():
            if value in canonical_values:
                lines.append(f"    {name} = {value}  # alias of {canonical_values[value]}")
            else:
                canonical_values[value] = name
                lines.append(f"    {name} = {value}")
    return "\n".join(lines) + "\n"


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--write", action="store_true", help="rewrite Expedition/enums.py")
    args = parser.parse_args(argv)

    missing = find_missing_headers(REFERENCE_DIR)
    if missing:
        print(
            f"Missing headers in {REFERENCE_DIR}: {', '.join(missing)}. "
            "Run scripts/sync_expedition_headers.py first.",
            file=sys.stderr,
        )
        return 1

    enums = load_enums(REFERENCE_DIR)
    text = render(enums, "reference/expedition (gitignored)")
    if args.write:
        OUTPUT_PATH.write_text(text, encoding="utf-8")
        print(f"Wrote {OUTPUT_PATH}")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
